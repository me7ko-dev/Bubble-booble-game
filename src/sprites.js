// ─── Балончета (генерирани по формула) ─────────────────────
function bubbleCanvas(ring, fill, fillAlpha = 0.28) {
  const c = makeCanvas(16, 16);
  const g = c.getContext('2d');
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      const d = Math.hypot(x - 7.5, y - 7.5);
      if (d <= 7.6 && d > 6.1) { g.globalAlpha = 1; g.fillStyle = ring; g.fillRect(x, y, 1, 1); }
      else if (d <= 6.1) { g.globalAlpha = fillAlpha; g.fillStyle = fill; g.fillRect(x, y, 1, 1); }
    }
  }
  g.globalAlpha = 1;
  g.fillStyle = '#fff';
  g.fillRect(4, 3, 2, 1); g.fillRect(3, 4, 1, 2); g.fillRect(4, 4, 1, 1);
  return c;
}

function pix(g, rows, ox, oy) {
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      g.fillStyle = PAL[ch] || ch;
      g.fillRect(ox + x, oy + y, 1, 1);
    }
  });
}

function specialBubble(ring, icon) {
  const c = bubbleCanvas(ring, ring, 0.35);
  pix(c.getContext('2d'), art(icon), 4, 4);
  return c;
}

