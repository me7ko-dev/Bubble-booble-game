function itemCanvas(str) {
  const rows = art(str);
  const c = makeCanvas(16, 16);
  pix(c.getContext('2d'), rows, 0, 16 - rows.length);
  return c;
}

// ─── Шефът (48×48, рисуван с примитиви и изчистен до пиксели) ─
function bossCanvas(body, dark) {
  const c = makeCanvas(48, 48);
  const g = c.getContext('2d');
  const disk = (x, y, r, col) => {
    g.fillStyle = col;
    for (let yy = Math.floor(y - r); yy <= y + r; yy++)
      for (let xx = Math.floor(x - r); xx <= x + r; xx++)
        if (Math.hypot(xx + 0.5 - x, yy + 0.5 - y) <= r) g.fillRect(xx, yy, 1, 1);
  };
  disk(24, 26, 21, '#101018');
  disk(24, 26, 20, body);
  disk(24, 34, 13, dark);
  // очи
  disk(15, 18, 6, '#101018'); disk(15, 18, 5, '#fff'); disk(17, 19, 2.2, '#101018');
  disk(33, 18, 6, '#101018'); disk(33, 18, 5, '#fff'); disk(35, 19, 2.2, '#101018');
  // зли вежди
  g.fillStyle = '#101018';
  for (let i = 0; i < 8; i++) { g.fillRect(9 + i, 10 + (i >> 1), 1, 2); g.fillRect(38 - i, 10 + (i >> 1), 1, 2); }
  // уста
  g.fillStyle = '#101018'; g.fillRect(14, 30, 20, 7);
  g.fillStyle = '#e83838'; g.fillRect(15, 31, 18, 5);
  g.fillStyle = '#fff';
  for (let i = 0; i < 4; i++) { g.fillRect(16 + i * 5, 31, 3, 2); g.fillRect(18 + i * 4, 34, 2, 2); }
  // корона
  g.fillStyle = '#101018'; g.fillRect(13, 2, 22, 6);
  g.fillStyle = '#ffe040'; g.fillRect(14, 3, 20, 4);
  for (let i = 0; i < 3; i++) { g.fillStyle = '#101018'; g.fillRect(14 + i * 9, -1 + 0, 4, 3); g.fillStyle = '#ffe040'; g.fillRect(15 + i * 9, 0, 2, 3); }
  g.fillStyle = '#e83838'; g.fillRect(23, 4, 2, 2);
  return c;
}

