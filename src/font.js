const cache = new Map(); // цвят → Map(знак → canvas)

function glyph(ch, color) {
  let byColor = cache.get(color);
  if (!byColor) { byColor = new Map(); cache.set(color, byColor); }
  let c = byColor.get(ch);
  if (c) return c;
  const rows = G[ch] || G[ch.toUpperCase()] || G['?'];
  c = document.createElement('canvas');
  c.width = 5; c.height = 7;
  const g = c.getContext('2d');
  g.fillStyle = color;
  rows.forEach((row, y) => {
    for (let x = 0; x < 5; x++) if (row[x] === '#') g.fillRect(x, y, 1, 1);
  });
  byColor.set(ch, c);
  return c;
}

export const CHAR_W = 6;

export function textWidth(str, scale = 1) {
  return str.length * CHAR_W * scale - scale;
}

// Рисува текст; align: 'left' | 'center' | 'right'. shadow – цвят на сянка или null.
export function drawText(ctx, str, x, y, color = '#fff', { align = 'left', scale = 1, shadow = '#000' } = {}) {
  str = String(str).toUpperCase();
  const w = textWidth(str, scale);
  let sx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  y = Math.round(y);
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    if (ch !== ' ') {
      if (shadow) ctx.drawImage(glyph(ch, shadow), sx + scale, y + scale, 5 * scale, 7 * scale);
      ctx.drawImage(glyph(ch, color), sx, y, 5 * scale, 7 * scale);
    }
    sx += CHAR_W * scale;
  }
}
